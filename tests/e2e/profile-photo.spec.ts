import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { randomUUID } from "node:crypto";
import sharp from "sharp";
import { removeTestAccount } from "./database";

test("profile photo upload, replacement and removal persist privately with initials fallback", async ({ page, browser }, testInfo) => {
  const email = `e2e-${randomUUID()}@example.invalid`;
  const password = randomUUID();
  const otherEmail = `e2e-${randomUUID()}@example.invalid`;
  const anonymous = await browser.newContext({ ignoreHTTPSErrors: true });
  try {
    await page.goto("/register");
    await page.getByLabel("Name", { exact: true }).fill("Photo owner");
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Register", exact: true }).click();
    await expect(page).toHaveURL((url) => url.pathname === "/login");
    await page.goto("/login");
    await page.getByLabel("Email", { exact: true }).fill(email);
    await page.getByLabel("Password", { exact: true }).fill(password);
    await page.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await page.goto("/app");
    const origin = new URL(page.url()).origin;
    const route = `${origin}/api/account/photo`;
    expect((await anonymous.request.get(route)).status()).toBe(401);
    expect((await page.request.get(route)).status()).toBe(404);
    const input = page.getByLabel("Profile photo", { exact: true });
    await expect(input).toBeEnabled();
    const photoForm = input.locator("xpath=ancestor::form");
    await input.setInputFiles({ name: "bad.svg", mimeType: "image/svg+xml", buffer: Buffer.from("<svg/>") });
    await expect(page.getByRole("main").getByRole("alert")).toContainText("up to 2 MB");
    expect(await input.evaluate((node: HTMLInputElement) => node.validity.valid)).toBe(false);
    const source = await sharp({ create: { width: 500, height: 400, channels: 3, background: "#8274c9" } }).png().toBuffer();
    const file = { name: "synthetic.png", mimeType: "image/png", buffer: source };
    await input.setInputFiles(file);
    await page.getByRole("button", { name: "Upload photo", exact: true }).click();
    await expect(photoForm.getByRole("status")).toContainText("Your profile photo has been updated");
    const avatar = page.getByRole("main").getByRole("img", { name: "Photo owner's profile photo" });
    await expect(avatar).toBeVisible();
    await expect(avatar).toHaveJSProperty("naturalWidth", 256);
    const first = await avatar.getAttribute("src");
    const response = await page.request.get(route);
    expect(response.status()).toBe(200);
    expect(response.headers()["content-type"]).toBe("image/webp");
    expect(response.headers()["cache-control"]).toBe("private, no-store");
    expect(response.headers()["x-content-type-options"]).toBe("nosniff");
    const metadata = await sharp(await response.body()).metadata();
    expect([metadata.width, metadata.height]).toEqual([256, 256]);
    expect(metadata.exif).toBeUndefined();
    await page.reload();
    await expect(avatar).toBeVisible();
    await expect(page.getByRole("button", { name: "Open profile menu" }).getByRole("img")).toBeVisible();
    const back = page.getByRole("link", { name: "Back to dashboard", exact: true });
    await expect(back.locator("svg")).toHaveAttribute("aria-hidden", "true");
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("profile-photo.png"), fullPage: true });
    await input.setInputFiles(file);
    await page.getByRole("button", { name: "Upload photo", exact: true }).click();
    await expect(avatar).not.toHaveAttribute("src", first!);
    expect((await anonymous.request.get(`${origin}${first}`)).status()).toBe(401);
    const other = await anonymous.newPage();
    await other.goto(`${origin}/register`);
    await other.getByLabel("Name", { exact: true }).fill("Other owner");
    await other.getByLabel("Email", { exact: true }).fill(otherEmail);
    await other.getByLabel("Password", { exact: true }).fill(password);
    await other.getByRole("button", { name: "Register", exact: true }).click();
    await expect(other).toHaveURL((url) => url.pathname === "/login");
    await other.goto(`${origin}/login`);
    await other.getByLabel("Email", { exact: true }).fill(otherEmail);
    await other.getByLabel("Password", { exact: true }).fill(password);
    await other.getByRole("button", { name: "Sign in", exact: true }).click();
    await expect(other).toHaveURL(/\/dashboard$/);
    expect((await anonymous.request.get(`${origin}${first}`)).status()).toBe(404);
    await page.getByRole("button", { name: "Remove photo", exact: true }).click();
    await expect(photoForm.getByRole("status")).toContainText("Your profile photo has been removed");
    await expect(avatar).toHaveCount(0);
    expect((await page.request.get(`${route}?v=${randomUUID()}`)).status()).toBe(404);
    await page.reload();
    await expect(page.getByRole("button", { name: "Remove photo", exact: true })).toHaveCount(0);
    await back.click();
    await expect(page).toHaveURL(/\/dashboard$/);
  } finally {
    await anonymous.close();
    await removeTestAccount(email);
    await removeTestAccount(otherEmail);
  }
});
